import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const policy = JSON.parse(await readFile(path.join(root, 'docs/capture-policy.json'), 'utf8'));
const ids = ['compressed', 'documents', 'music', 'programs', 'video', 'other'];
if (policy.schemaVersion !== 1 || JSON.stringify(policy.categories.map(c => c.id)) !== JSON.stringify(ids) ||
    policy.classification.knownLastExtensionFirst !== true || policy.classification.unknownTarSuffixCategory !== 'compressed' ||
    policy.classification.fallbackCategory !== 'other') throw new Error('Unsupported capture catalog');
const seen = new Set();
for (const category of policy.categories) {
  if (category.category !== category.id[0].toUpperCase() + category.id.slice(1)) throw new Error('Unstable category name');
  for (const extension of category.extensions) {
    if (!/^[a-z0-9]{1,16}$/.test(extension) || seen.has(extension)) throw new Error('Invalid or duplicate extension');
    seen.add(extension);
  }
}
if (policy.categories.at(-1).extensions.length || policy.legacyCaptureExtensions.length > 256 ||
    new Set(policy.legacyCaptureExtensions).size !== policy.legacyCaptureExtensions.length ||
    policy.legacyCaptureExtensions.some(e => !seen.has(e))) throw new Error('Invalid capture defaults');
if (!policy.decisionReasons || Object.keys(policy.decisionReasons).length > 32 ||
    Object.entries(policy.decisionReasons).some(([key, value]) => !/^[a-z][a-zA-Z]{0,31}$/.test(key) || !/^[a-z-]{1,32}$/.test(value)) ||
    new Set(Object.values(policy.decisionReasons)).size !== Object.keys(policy.decisionReasons).length) throw new Error('Invalid capture reasons');
const quote = value => JSON.stringify(value);
const cs = `// Generated by scripts/generate-capture-policy.mjs. Edit docs/capture-policy.json.
using Colibri.Core.Models;

namespace Colibri.Core.Services;

public static class CaptureCatalog
{
    public static class Reasons
    {
${Object.entries(policy.decisionReasons).map(([key, value]) => `        public const string ${key[0].toUpperCase() + key.slice(1)} = ${quote(value)};`).join('\n')}
    }
    public sealed record CategoryDefinition(string Id, DownloadCategory Category, IReadOnlyList<string> Extensions);
    public static IReadOnlyList<CategoryDefinition> Categories { get; } = Array.AsReadOnly<CategoryDefinition>([
${policy.categories.map(c => `        new(${quote(c.id)}, DownloadCategory.${c.category}, Array.AsReadOnly<string>([${c.extensions.map(quote).join(', ')}])),`).join('\n')}
    ]);
    public static IReadOnlyList<string> LegacyCaptureExtensions { get; } = Array.AsReadOnly<string>([${policy.legacyCaptureExtensions.map(quote).join(', ')}]);
}
`;
const ts = `// Generated by Colibri/scripts/generate-capture-policy.mjs. Edit the app-owned docs/capture-policy.json.
export const captureCatalog = ${JSON.stringify(policy, null, 2)} as const;
export const captureReasons = captureCatalog.decisionReasons;
export type CaptureReason = typeof captureReasons[keyof typeof captureReasons];
export function fileBaseName(fileName: string): string {
  return fileName.replaceAll(String.fromCharCode(92), '/').split('/').at(-1) ?? '';
}
export function fileExtension(fileName: string): string {
  const name = fileBaseName(fileName); const dot = name.lastIndexOf('.');
  return dot > 0 && dot < name.length - 1 ? name.slice(dot + 1).toLowerCase() : '';
}
export type CaptureCategoryId = typeof captureCatalog.categories[number]['id'];
const byExtension = new Map<string, CaptureCategoryId>(captureCatalog.categories.flatMap(c => c.extensions.map(e => [e, c.id] as const)));
export function categoryForFileName(fileName: string): CaptureCategoryId {
  const parts = fileBaseName(fileName).split('.');
  if (parts.length < 2) return captureCatalog.classification.fallbackCategory;
  const known = byExtension.get(parts[parts.length - 1]!.toLowerCase());
  if (known) return known;
  if (parts.length >= 3 && parts[parts.length - 2]!.toLowerCase() === 'tar') return captureCatalog.classification.unknownTarSuffixCategory;
  return captureCatalog.classification.fallbackCategory;
}
`;
const outputs = new Map([
  ['src/Colibri.Core/Services/CaptureCatalog.cs', cs],
  ['docs/capture-catalog.ts', ts],
  ['../colibri-browser-integration/src/generated/capture-catalog.ts', ts],
  ['../colibri-browser-integration/src/generated/capture-rules.ts', await readFile(path.join(root, 'docs/capture-rules.ts'), 'utf8').then(s => s.replaceAll('\r\n', '\n'))],
  ['../colibri-browser-integration/docs/capture-policy.json', await readFile(path.join(root, 'docs/capture-policy.json'), 'utf8').then(s => s.replaceAll('\r\n', '\n'))],
]);
for (const [relative, content] of outputs) {
  const target = path.join(root, relative);
  if (process.argv.includes('--check')) {
    if ((await readFile(target, 'utf8')).replaceAll('\r\n', '\n') !== content) throw new Error(`Capture catalog drift: ${relative}`);
  } else await writeFile(target, content);
}
