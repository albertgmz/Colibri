import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(await readFile(path.join(root, 'docs/design-tokens.json'), 'utf8'));
const extension = process.argv[2];
const dictionaries = ['Light', 'Dark'].map(theme => {
  const values = tokens[theme.toLowerCase()];
  return `    <ResourceDictionary x:Key="${theme}">\n` +
    [['ChromeBackgroundBrush', values.chrome], ['ContentPaneBrush', values.surface], ['DividerBrush', values.divider]]
      .map(([key, color]) => `      <SolidColorBrush x:Key="${key}" Color="${color}" />`).join('\n') +
    '\n    </ResourceDictionary>';
}).join('\n');
const xaml = `<!-- Generated by scripts/generate-design-tokens.mjs. -->
<ResourceDictionary xmlns="https://github.com/avaloniaui" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
  <Color x:Key="ColibriDefaultAccent">${tokens.accent}</Color>
  <x:Double x:Key="ColibriBodySize">${tokens.type.body}</x:Double>
  <CornerRadius x:Key="ColibriCornerRadius">${tokens.radius}</CornerRadius>
  <ResourceDictionary.ThemeDictionaries>
${dictionaries}
  </ResourceDictionary.ThemeDictionaries>
</ResourceDictionary>
`;
await writeFile(path.join(root, 'src/Colibri.App/Resources/DesignTokens.axaml'), xaml);
// Avalonia uses AARRGGBB; CSS uses RRGGBBAA for eight-digit colors.
const cssColor = value => /^#[0-9a-f]{8}$/i.test(value) ? `#${value.slice(3)}${value.slice(1, 3)}` : value;
const cssTheme = theme => Object.entries(tokens[theme]).map(([key, value]) => `  --colibri-${key}: ${cssColor(value)};`).join('\n');
const css = `/* Generated from Colibri/docs/design-tokens.json. */
:root {
  --colibri-accent: ${tokens.accent};
  --colibri-radius: ${tokens.radius}px;
  --colibri-space-small: ${tokens.spacing.small}px;
  --colibri-space-medium: ${tokens.spacing.medium}px;
  --colibri-space-large: ${tokens.spacing.large}px;
  --colibri-font: ${tokens.type.family};
  --colibri-type-small: ${tokens.type.small}px;
  --colibri-type-body: ${tokens.type.body}px;
  --colibri-type-title: ${tokens.type.title}px;
${cssTheme('light')}
}
@media (prefers-color-scheme: dark) { :root {
${cssTheme('dark')}
} }
:root[data-theme="dark"] {
${cssTheme('dark')}
}
:root[data-theme="light"] {
${cssTheme('light')}
}
`;
await writeFile(path.join(root, 'docs/design-tokens.css'), css);
if (extension) await writeFile(path.resolve(extension), css);
