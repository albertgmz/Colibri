import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(await readFile(path.join(root, 'docs/design-tokens.json'), 'utf8'));
const extension = process.argv[2];
const brushes = { ChromeBackgroundBrush: 'chrome', ContentPaneBrush: 'surface', DividerBrush: 'divider',
  CardBrush: 'card', ContentPaneMicaBrush: 'mica', ChromeMicaBrush: 'chromeMica' };
for (const variant of ['light', 'dark']) {
  if (JSON.stringify(tokens[variant]) !== JSON.stringify(tokens.palettes.warm[variant])) throw new Error('Warm defaults drifted');
}
for (const id of ['warm', 'graphite', 'ocean', 'forest']) for (const variant of ['light', 'dark']) {
  for (const key of ['chrome','surface','text','divider','card','mica','chromeMica']) {
    if (!/^#[0-9a-f]{6}([0-9a-f]{2})?$/i.test(tokens.palettes[id]?.[variant]?.[key])) throw new Error(`Invalid ${id}/${variant}/${key}`);
  }
}
const dictionaries = ['Light', 'Dark'].map(theme => {
  const values = tokens[theme.toLowerCase()];
  return `    <ResourceDictionary x:Key="${theme}">\n` +
    Object.entries(brushes).map(([key, token]) => [key, values[token]])
      .map(([key, color]) => `      <SolidColorBrush x:Key="${key}" Color="${color}" />`).join('\n') +
    '\n    </ResourceDictionary>';
}).join('\n');
const xaml = `<!-- Generated by scripts/generate-design-tokens.mjs. -->
<ResourceDictionary xmlns="https://github.com/avaloniaui" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
  <Color x:Key="ColibriDefaultAccent">${tokens.accent}</Color>
  <x:Double x:Key="ColibriBodySize">${tokens.type.body}</x:Double>
  <CornerRadius x:Key="ColibriCornerRadius">${tokens.radius}</CornerRadius>
  <ResourceDictionary.ThemeDictionaries>
${dictionaries}
  </ResourceDictionary.ThemeDictionaries>
</ResourceDictionary>
`;
await writeFile(path.join(root, 'src/Colibri.App/Resources/DesignTokens.axaml'), xaml);
const cases = Object.entries(tokens.palettes).map(([id, variants]) =>
  `            "${id}" => (${['light', 'dark'].map(variant => `new SurfaceColors(${['chrome','surface','card','divider','mica','chromeMica'].map(key => `"${variants[variant][key]}"`).join(', ')})`).join(', ')}),`).join('\n');
await writeFile(path.join(root, 'src/Colibri.App/Resources/DesignPalettes.cs'), `// Generated by scripts/generate-design-tokens.mjs.
using Avalonia.Controls;
using Avalonia.Media;
using Avalonia.Styling;
using Colibri.Core.Settings;

namespace Colibri.App.Resources;

internal static class DesignPalettes
{
    internal sealed record SurfaceColors(string Chrome, string Pane, string Card, string Divider, string Mica, string ChromeMica);
    internal static (SurfaceColors Light, SurfaceColors Dark) Get(string id) => BackgroundPalettes.Normalize(id) switch
    {
${cases}
            _ => throw new System.InvalidOperationException()
    };

    internal static ResourceDictionary Create(string id)
    {
        var colors = Get(id);
        var dictionary = new ResourceDictionary();
        dictionary.ThemeDictionaries[ThemeVariant.Light] = CreateVariant(colors.Light);
        dictionary.ThemeDictionaries[ThemeVariant.Dark] = CreateVariant(colors.Dark);
        return dictionary;
    }

    private static ResourceDictionary CreateVariant(SurfaceColors colors) => new()
    {
        ["ChromeBackgroundBrush"] = new SolidColorBrush(Color.Parse(colors.Chrome)),
        ["ContentPaneBrush"] = new SolidColorBrush(Color.Parse(colors.Pane)),
        ["CardBrush"] = new SolidColorBrush(Color.Parse(colors.Card)),
        ["DividerBrush"] = new SolidColorBrush(Color.Parse(colors.Divider)),
        ["ContentPaneMicaBrush"] = new SolidColorBrush(Color.Parse(colors.Mica)),
        ["ChromeMicaBrush"] = new SolidColorBrush(Color.Parse(colors.ChromeMica))
    };
}
`);
// Avalonia uses AARRGGBB; CSS uses RRGGBBAA for eight-digit colors.
const cssColor = value => /^#[0-9a-f]{8}$/i.test(value) ? `#${value.slice(3)}${value.slice(1, 3)}` : value;
const cssTheme = theme => Object.entries(tokens[theme]).map(([key, value]) => `  --colibri-${key}: ${cssColor(value)};`).join('\n');
const paletteVariables = (id, variant) => Object.entries(tokens.palettes[id][variant]).map(([key,value]) => `  --colibri-${key}: ${cssColor(value)};`).join('\n');
const paletteCss = Object.keys(tokens.palettes).map(id => `:root[data-palette="${id}"] {\n${paletteVariables(id,'light')}\n}\n@media (prefers-color-scheme: dark) { :root[data-palette="${id}"] {\n${paletteVariables(id,'dark')}\n} }\n:root[data-palette="${id}"][data-theme="dark"] {\n${paletteVariables(id,'dark')}\n}\n:root[data-palette="${id}"][data-theme="light"] {\n${paletteVariables(id,'light')}\n}`).join('\n');
const css = `/* Generated from Colibri/docs/design-tokens.json. */
:root {
  --colibri-accent: ${tokens.accent};
  --colibri-radius: ${tokens.radius}px;
  --colibri-space-small: ${tokens.spacing.small}px;
  --colibri-space-medium: ${tokens.spacing.medium}px;
  --colibri-space-large: ${tokens.spacing.large}px;
  --colibri-font: ${tokens.type.family};
  --colibri-type-small: ${tokens.type.small}px;
  --colibri-type-body: ${tokens.type.body}px;
  --colibri-type-title: ${tokens.type.title}px;
${cssTheme('light')}
}
@media (prefers-color-scheme: dark) { :root {
${cssTheme('dark')}
} }
:root[data-theme="dark"] {
${cssTheme('dark')}
}
:root[data-theme="light"] {
${cssTheme('light')}
}
${paletteCss}
`;
await writeFile(path.join(root, 'docs/design-tokens.css'), css);
if (extension) await writeFile(path.resolve(extension), css);
